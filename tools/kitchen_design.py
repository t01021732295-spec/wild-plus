"""2.19 도안: 조리 기구 5종 + 숙성통 + 식당 카운터 (여러 칸짜리 3D 블록).
좌표는 픽셀 (16 = 블록 한 칸). x 오른쪽, y 위, z 앞(+z 가 정면). 바닥 y=0."""
from cosmetic_design import Box, mix, shade


def C(c):
    return lambda *a: c


def bricks(c1, c2, mortar=(70, 60, 55), bw=4, bh=2):
    def f(face, u, v, W, H):
        if face in ("top", "bottom"):
            return shade(c1, 0.95)
        row = v // bh
        if v % bh == bh - 1:
            return mortar
        off = (row % 2) * (bw // 2)
        if (u + off) % bw == bw - 1:
            return mortar
        return c1 if (row + (u + off) // bw) % 3 else c2
    return f


def planks(c, line=None):
    line = line or shade(c, 0.72)
    def f(face, u, v, W, H):
        if face in ("front", "back", "left", "right"):
            if v % 4 == 3:
                return line
            return c if (u * 7 + v // 4 * 3) % 11 else shade(c, 0.9)
        return shade(c, 1.08) if (u + v) % 5 else c
    return f


def metal(c, rivet=None):
    def f(face, u, v, W, H):
        if rivet and face == "front" and (u in (1, W - 2)) and (v in (1, H - 2)):
            return rivet
        if face == "top":
            return shade(c, 1.15)
        return mix(shade(c, 1.05), shade(c, 0.78), v / max(1, H - 1))
    return f


def glow(c1, c2):
    def f(face, u, v, W, H):
        return mix(c2, c1, v / max(1, H - 1)) if (u + v) % 3 else shade(c1, 1.1)
    return f


def stone(c):
    def f(face, u, v, W, H):
        return shade(c, 0.9) if (u * 3 + v * 5) % 7 == 0 else c
    return f


def marble(face, u, v, W, H):
    return (236, 232, 228) if (u + 2 * v) % 9 else (205, 200, 196)


STEAM_BOXES = True
FIRE = glow((255, 220, 90), (230, 80, 20))
STEAM = C((240, 240, 245))
WOOD = (150, 100, 55)
DARKWOOD = (90, 58, 32)


def logs(x, y, z, n=3, w=12):
    out = []
    for k in range(n):
        out.append(Box(x, y + k * 3, z + (k % 2), w, 3, 3, planks((120, 80, 45), (80, 50, 25))))
        out.append(Box(x - 0.2, y + k * 3, z + (k % 2), 0.2, 3, 3, C((200, 170, 120))))
    return out


# ───────── 1. 가마솥 (냄비): 벽돌 아궁이 위 무쇠 솥 · 2칸 ─────────
def cauldron():
    out = [Box(-16, 0, -8, 32, 14, 16, bricks((168, 74, 52), (150, 64, 46)))]
    # 아궁이 입구 (불)
    out += [Box(-6, 1, 7.9, 12, 8, 0.4, C((30, 20, 18))), Box(-5, 1, 8.2, 10, 6, 0.3, FIRE),
            Box(-7, 9, 8, 14, 1.5, 1, C((90, 80, 75)))]
    out += logs(-4, 1, 6, 1, 8)
    # 솥: 둥글게 (층마다 폭 다르게)
    pot = metal((52, 52, 58))
    for (y, w, d) in [(14, 16, 12), (15.5, 20, 14), (19, 22, 15), (23, 20, 14)]:
        out.append(Box(-w / 2, y, -d / 2, w, 3.5 if y < 23 else 2, d, pot))
    out += [Box(-12, 24.5, -8, 24, 1.2, 16, metal((80, 80, 88)))]  # 테
    out += [Box(-10, 25.6, -6.5, 20, 0.6, 13, C((214, 120, 60)))]  # 끓는 국물
    out += [Box(-12, 26, -1, 9, 1, 9, planks((140, 92, 52)))]  # 뚜껑 반쯤
    out += [Box(5, 25.8, -1, 1.2, 9, 1.2, planks(WOOD), rot=("z", -0.5, (5.6, 26, 0)))]  # 국자
    # 손잡이 고리
    out += [Box(-13.5, 21, -1, 1.5, 3, 2, C((40, 40, 46))), Box(12, 21, -1, 1.5, 3, 2, C((40, 40, 46)))]
    # 굴뚝 (뒤 오른쪽)
    out += [Box(10, 14, -8, 5, 18, 5, bricks((150, 64, 46), (130, 56, 40))), Box(9.5, 32, -8.5, 6, 1.5, 6, C((90, 80, 75)))]
    # 김 (도안에서만 · 게임에선 입자)
    if STEAM_BOXES:
        out += [Box(-3, 30, -2, 3, 3, 3, STEAM), Box(1, 33, 0, 4, 3, 3, STEAM), Box(-1, 37, -1, 3, 2, 3, STEAM)]
    return out


# ───────── 2. 화덕 오븐: 2×2 벽돌 돔 · 아치 입구 ─────────
def oven():
    b = bricks((190, 120, 80), (170, 104, 70), (110, 90, 80))
    out = [Box(-16, 0, -16, 32, 8, 32, stone((130, 128, 124)))]  # 돌 받침
    for (y, w) in [(8, 30), (14, 26), (19, 20), (23, 13)]:
        out.append(Box(-w / 2, y, -w / 2, w, 6 if y < 23 else 4, w, b))
    # 입구 아치 + 안쪽 불빛
    out += [Box(-6, 9, 13, 12, 9, 2.2, C((40, 24, 18))), Box(-5, 9, 14.6, 10, 6, 0.6, FIRE),
            Box(-7, 18, 13.5, 14, 2, 2.5, C((120, 90, 70))), Box(-8, 8, 13, 16, 1, 3.5, C((100, 96, 92)))]
    # 굴뚝
    out += [Box(-3, 27, -3, 6, 9, 6, metal((70, 70, 74))), Box(-4, 36, -4, 8, 1.5, 8, C((50, 50, 54)))]
    # 피자 삽 (기대어 둠) + 장작더미
    out += [Box(10, 0, 15.5, 1.2, 22, 1.2, planks(WOOD), rot=("z", 0.25, (10, 0, 16))),
            Box(5, 17, 15, 8, 0.8, 7, planks((200, 160, 110)), rot=("z", 0.25, (10, 0, 16)))]
    out += logs(-17, 0, 17, 3, 10)
    return out


# ───────── 3. 바비큐 그릴: 2칸 · 숯불 · 꼬치 ─────────
def grill():
    red = metal((180, 40, 36), (60, 60, 64))
    out = []
    for (x, z) in [(-14, -6), (12, -6), (-14, 4), (12, 4)]:
        out.append(Box(x, 0, z, 2, 12, 2, metal((50, 50, 54))))
    out += [Box(-15, 12, -7, 30, 7, 14, red)]  # 몸통
    out += [Box(-14, 18, -6, 28, 1.2, 12, glow((255, 140, 40), (140, 30, 10)))]  # 숯
    for k in range(9):
        out.append(Box(-14, 19.6, -6 + k * 1.5, 28, 0.5, 0.4, C((40, 40, 44))))  # 석쇠
    # 꼬치 3개 + 스테이크
    for k, c in enumerate([(200, 80, 50), (120, 170, 60), (230, 200, 90)]):
        x = -12 + k * 5
        out += [Box(x, 20.2, -7, 0.4, 0.4, 14, C((200, 180, 140)))]
        for j in range(4):
            out.append(Box(x - 1, 20.2, -4 + j * 3, 2.2, 2, 2, C(c if j % 2 else (190, 110, 70))))
    out += [Box(4, 20.2, -4, 8, 1.5, 7, C((150, 70, 45))), Box(5, 21.7, -3, 6, 0.3, 5, C((120, 50, 30)))]
    # 옆 선반 + 접시 · 뚜껑(뒤로 열림)
    out += [Box(15, 15, -6, 8, 1.2, 12, planks(WOOD)), Box(17, 16.2, -3, 5, 0.6, 5, C((240, 240, 236)))]
    out += [Box(-15, 19, -9, 30, 10, 1.5, red, rot=("x", -0.35, (0, 19, -7)))]
    return out


# ───────── 4. 도마 작업대: 2칸 수납장 + 큰 도마 + 칼 + 채소 + 걸이 ─────────
def prep():
    out = [Box(-16, 0, -8, 32, 14, 16, planks((170, 120, 70)))]
    for (x0, y0) in [(-15, 7.5), (-15, 1), (1, 7.5), (1, 1)]:  # 서랍 4개
        out += [Box(x0, y0, 7.9, 14, 5.5, 0.5, planks((190, 140, 85))), Box(x0 + 5, y0 + 2.5, 8.4, 4, 1, 0.8, C((60, 60, 64)))]
    out += [Box(-17, 14, -9, 34, 2, 18, marble)]  # 상판
    out += [Box(-12, 16, -5, 18, 1.5, 10, planks((205, 160, 105), (180, 135, 85)))]  # 도마
    out += [Box(-2, 17.5, -2, 9, 0.4, 2, C((210, 215, 222))), Box(-6, 17.3, -2, 4, 1, 2, C((40, 30, 24)))]  # 칼
    out += [Box(-10, 17.5, -3, 3, 3, 3, C((220, 50, 40))), Box(-9.5, 20.5, -2, 1, 1, 1, C((70, 140, 50)))]  # 토마토
    out += [Box(8, 16, -4, 4, 4, 4, C((225, 175, 110))), Box(9.5, 20, -2.5, 1, 2, 1, C((90, 160, 60)))]  # 양파
    out += [Box(12, 16, 1, 5, 4, 5, C((120, 190, 80)))]  # 양배추
    # 뒤 벽 걸이: 막대 + 국자 · 뒤집개 · 냄비
    out += [Box(-16, 26, -9, 32, 1, 1, metal((80, 80, 86)))]
    for (x, h, c) in [(-12, 8, (200, 200, 205)), (-6, 7, (150, 100, 60)), (0, 9, (200, 200, 205))]:
        out.append(Box(x, 26 - h, -8.8, 1.5, h, 0.8, C(c)))
    out += [Box(5, 19, -9, 8, 6, 2, metal((60, 60, 66)))]
    return out


# ───────── 5. 화구 (스토브): 1칸 · 화구 2개 + 프라이팬 ─────────
def stove():
    out = [Box(-8, 0, -8, 16, 15, 16, metal((235, 235, 232)))]
    out += [Box(-6, 2, 7.9, 12, 8, 0.5, C((40, 40, 46))), Box(-5, 9, 8.3, 10, 0.8, 0.8, C((180, 180, 186)))]  # 오븐 문 · 손잡이
    for x in (-6, -2, 2, 6):  # 손잡이 다이얼
        out.append(Box(x - 0.8, 12, 7.9, 1.6, 1.6, 0.8, C((30, 30, 34))))
    out += [Box(-8, 15, -8, 16, 0.8, 16, C((30, 30, 34)))]
    out += [Box(-6.5, 15.8, -6, 5, 0.4, 5, glow((120, 180, 255), (40, 80, 220))), Box(1.5, 15.8, 1, 5, 0.4, 5, glow((120, 180, 255), (40, 80, 220)))]
    # 프라이팬 + 계란 + 손잡이
    out += [Box(-7.5, 16.2, -7, 7, 1.5, 7, metal((50, 50, 56))), Box(-6, 17.2, -5.5, 4, 0.3, 4, C((250, 250, 245))),
            Box(-4.7, 17.4, -4.2, 1.5, 0.4, 1.5, C((255, 190, 40))), Box(-0.5, 16.8, -4.5, 7, 0.8, 1.4, C((40, 30, 24)))]
    # 냄비 (뒤)
    out += [Box(1, 16.2, -7, 6, 4, 6, metal((170, 170, 176))), Box(0.5, 20.2, -7.5, 7, 0.6, 7, C((140, 140, 146)))]
    # 뒤 판 + 환풍구
    out += [Box(-8, 15, -9, 16, 10, 1, metal((210, 210, 214))), Box(-5, 20, -8.2, 10, 3, 0.3, C((60, 60, 66)))]
    return out


# ───────── 6. 숙성통 선반: 2칸 · 누운 통 2개 + 꼭지 ─────────
def aging():
    out = []
    for x in (-16, 14):
        out.append(Box(x, 0, -8, 2, 30, 16, planks(DARKWOOD)))
    for y in (0, 14, 28):
        out.append(Box(-14, y, -8, 28, 2, 16, planks(DARKWOOD)))
    for (y, c) in [(2, (150, 95, 50)), (16, (130, 82, 44))]:
        # 통: 가로로 누운 원통 근사 (가운데 굵게)
        out += [Box(-12, y + 1, -7, 24, 10, 14, planks(c, shade(c, 0.7))), Box(-12.5, y + 2, -6, 25, 8, 12, planks(c, shade(c, 0.7)))]
        for x in (-9, 0, 9):
            out.append(Box(x, y + 0.8, -7.2, 1, 10.4, 14.4, C((70, 70, 76))))  # 쇠테
        out += [Box(-1, y + 4, 7, 2, 2, 2, C((200, 170, 60))), Box(-0.5, y + 3, 8.5, 1, 1.5, 1, C((200, 170, 60)))]  # 꼭지
    out += [Box(-10, 30, -3, 2.5, 5, 2.5, C((110, 40, 60))), Box(-6, 30, -3, 2.5, 6, 2.5, C((60, 120, 60))),
            Box(5, 30, -3, 4, 4, 4, C((240, 230, 200)))]  # 병 · 치즈
    return out


# ───────── 7. 식당 카운터: 3칸 계산대 + 진열장 + 위 칠판 메뉴판 ─────────
def counter():
    out = [Box(-24, 0, -8, 48, 15, 16, planks((150, 95, 55)))]
    for x in range(-23, 23, 6):
        out.append(Box(x, 1, 7.9, 5, 13, 0.4, planks((175, 115, 65))))  # 앞 판넬
    out += [Box(-25, 15, -9, 50, 2, 18, marble)]
    # 진열장 (왼쪽): 유리 상자 + 케이크 · 빵
    out += [Box(-23, 17, -6, 18, 10, 12, C((200, 230, 245)))]
    out += [Box(-21, 18, -3, 5, 4, 5, C((250, 230, 240))), Box(-21, 22, -3, 5, 1, 5, C((230, 60, 90))),
            Box(-14, 18, -3, 6, 3, 4, C((210, 150, 80))), Box(-9, 18, -4, 3, 3, 3, C((240, 200, 120)))]
    out += [Box(-23, 27, -6, 18, 0.6, 12, C((180, 180, 186)))]
    # 계산기 (가운데) + 종 (오른쪽)
    out += [Box(-2, 17, -4, 8, 5, 7, metal((60, 60, 66))), Box(-1, 22, -3, 6, 3, 1, C((40, 220, 140))), Box(-1, 17, 3, 6, 1, 2, C((200, 200, 205)))]
    out += [Box(14, 17, 0, 4, 0.6, 4, C((200, 160, 60))), Box(14.8, 17.6, 0.8, 2.4, 1.6, 2.4, C((240, 200, 80)))]
    # 메뉴판: 기둥 두 개 + 칠판
    for x in (-23, 21):
        out.append(Box(x, 17, -8, 2, 22, 2, planks(DARKWOOD)))
    out += [Box(-24, 30, -8.5, 48, 12, 1.5, planks(DARKWOOD)), Box(-22, 31, -7.2, 44, 10, 0.4, C((40, 60, 50)))]
    # 칠판 글씨 (분필 줄)
    for k, w in enumerate([18, 14, 16]):
        out.append(Box(-20, 38 - k * 3, -6.7, w, 0.8, 0.2, C((235, 235, 225))))
        out.append(Box(12, 38 - k * 3, -6.7, 6, 0.8, 0.2, C((255, 220, 120))))
    # 차양 (빨강·흰 줄무늬)
    stripe = lambda f, u, v, W, H: (220, 50, 50) if (u // 4) % 2 else (250, 250, 250)
    out += [Box(-26, 42, -10, 52, 1.5, 8, stripe, rot=("x", 0.35, (0, 43, -9)))]
    return out


