    out = [Box(-24, 0, -8, 48, 14, 16, planks((150, 95, 55)))]
    for x in range(-23, 23, 6):
        out.append(Box(x, 1, 7.9, 5, 12, 0.4, planks((175, 115, 65))))
    out += [Box(-25, 14, -9, 50, 2, 18, marble)]
    # 진열장 (왼쪽): 유리 + 케이크 · 빵
    out += [Box(-23, 16, -6, 18, 8, 12, C((200, 230, 245)))]
    out += [Box(-21, 17, -3, 5, 4, 5, C((250, 230, 240))), Box(-21, 21, -3, 5, 1, 5, C((230, 60, 90))),
            Box(-14, 17, -3, 6, 3, 4, C((210, 150, 80))), Box(-9, 17, -4, 3, 3, 3, C((240, 200, 120)))]
    out += [Box(-23, 24, -6, 18, 0.6, 12, C((180, 180, 186)))]
    # 계산기 · 종
    out += [Box(-2, 16, -4, 8, 5, 7, metal((60, 60, 66))), Box(-1, 21, -3, 6, 2.5, 1, C((40, 220, 140))), Box(-1, 16, 3, 6, 1, 2, C((200, 200, 205)))]
    out += [Box(14, 16, 2, 4, 0.6, 4, C((200, 160, 60))), Box(14.8, 16.6, 2.8, 2.4, 1.6, 2.4, C((240, 200, 80)))]
    # 메뉴판: 기둥 + 칠판 (뒤쪽)
    for x in (-24, 22):
        out.append(Box(x, 16, -8, 2, 14, 2, planks(DARKWOOD)))
